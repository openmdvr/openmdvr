async def test_new_subscription_bootstraps_and_bills_immediately(client, two_tenants, platform_users, pool):
    token = await login(client, platform_users["super_admin"]["email"])
    plan = await _create_plan(client, token, unit_price=190.0)
    tenant_id = two_tenants["a"]["tenant_id"]
    await _subscribe(client, token, tenant_id, plan_id=plan["id"], quantity=3)

    await _run_invoice_job(pool)

    resp = await client.get("/billing/invoices", params={"tenant_id": str(tenant_id)}, headers=auth_header(token))
    assert resp.status_code == 200
    items = resp.json()["items"]
    assert len(items) == 1
    invoice = items[0]
    assert invoice["subtotal"] == 570.0  # 3 * 190
    assert invoice["discount_total"] == 0.0
    assert invoice["total"] == 570.0
    assert invoice["status"] == "issued"
    assert len(invoice["line_items"]) == 1
    assert invoice["line_items"][0]["quantity"] == 3
    assert invoice["line_items"][0]["unit_price"] == 190.0


