async def test_numeric_overflow_for_one_tenant_does_not_block_others(client, two_tenants, platform_users, pool):
    """Security finding (HIGH): quantity * unit_price can overflow
    NUMERIC(12,2) inside generate_invoices(). Without the per-tenant
    BEGIN/EXCEPTION block in 0021_billing_invoices.sql, that overflow rolled
    back the ENTIRE job transaction -- including other tenants' invoices
    already inserted in the same run -- permanently blocking billing for the
    WHOLE platform (the poisoned tenant never advances next_invoice_date, so
    it qualifies again and breaks the job every day). This test confirms
    tenant B is invoiced normally even when tenant A overflows."""
    token = await login(client, platform_users["super_admin"]["email"])
    tenant_a = two_tenants["a"]["tenant_id"]
    tenant_b = two_tenants["b"]["tenant_id"]

    # unit_price_override and quantity are individually valid (each within
    # its own Pydantic bound), but their PRODUCT exceeds NUMERIC(12,2)
    # precision -- the combination a per-field bound cannot prevent.
    await _subscribe(client, token, tenant_a, custom_description="overflowing line", unit_price_override=9_999_999_999.99, quantity=100_000)
    plan_b = await _create_plan(client, token, unit_price=200.0)
    await _subscribe(client, token, tenant_b, plan_id=plan_b["id"], quantity=1)

    await _run_invoice_job(pool)

    resp_a = await client.get("/billing/invoices", params={"tenant_id": str(tenant_a)}, headers=auth_header(token))
    assert resp_a.json()["items"] == []  # tenant A: no invoice this cycle, retried tomorrow

    resp_b = await client.get("/billing/invoices", params={"tenant_id": str(tenant_b)}, headers=auth_header(token))
    items_b = resp_b.json()["items"]
    assert len(items_b) == 1
    assert items_b[0]["total"] == 200.0


