"""Billing -- promotions (tenant_promotions) + invoices
(invoices/invoice_line_items) generated by the generate_invoices PROCEDURE
(0021_billing_invoices.sql). Core concerns: the price snapshot is real
(changing a plan's price AFTER invoicing must not alter an already issued
invoice), promotions only apply inside their window, and tenant isolation
of invoices/invoice_line_items -- unlike billing_plans/tenant_promotions,
invoices ARE readable by the tenant's own tenant_admin (the basis of "My
billing"), so this also tests that read RLS works in that direction, not
only that it blocks."""
import uuid
from datetime import date, timedelta

import pytest

from conftest import TEST_PASSWORD, auth_header, login

pytestmark = pytest.mark.asyncio


async def _create_plan(client, token, unit_price=190.0, category="gps"):
    resp = await client.post(
        "/billing/plans",
        json={
            "name": f"Plan {uuid.uuid4().hex[:6]}",
            "sku": f"SKU-{uuid.uuid4().hex[:8]}",
            "category": category,
            "unit_price": unit_price,
            "currency": "MXN",
            "billing_period": "monthly",
        },
        headers=auth_header(token),
    )
    assert resp.status_code == 201, resp.text
    return resp.json()


async def _subscribe(
    client, token, tenant_id, plan_id=None, quantity=1, unit_price_override=None, custom_description=None, category=None
):
    body = {"tenant_id": str(tenant_id), "quantity": quantity}
    if plan_id is not None:
        body["billing_plan_id"] = plan_id
    if custom_description is not None:
        body["custom_description"] = custom_description
        # category is required on a line without a plan. Default 'addon' here
        # because these billing tests use custom lines for generic cases
        # (installation, precision overflow) that do not represent a real device
        # -- a caller that needs another category passes it explicitly.
        body["category"] = category or "addon"
    if unit_price_override is not None:
        body["unit_price_override"] = unit_price_override
    resp = await client.post("/billing/subscription-items", json=body, headers=auth_header(token))
    assert resp.status_code == 201, resp.text
    return resp.json()


async def _run_invoice_job(pool):
    from app import db as db_module

    async with db_module.tenant_scoped_connection(pool, tenant_id=None, bypass=True) as conn:
        await conn.execute("CALL generate_invoices(0, '{}'::jsonb)")


